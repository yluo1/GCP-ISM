%L = sinc(x) * sinc(x/a) for |x| <= a, otherwise 0

%Author: Yuancheng Luo, 2026

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%Input
%x:     [M x N]
%a:     Scalar

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%Output
%L:     [M x N]

function L = lanczos_kernel(x, a)
L = sinc(x) .* sinc(x / a);
L(abs(x) > a) = 0;
